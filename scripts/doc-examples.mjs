import { createHash } from 'node:crypto';
export function renderExamples(data, chinese = false) {
  const digest = createHash('sha256').update(JSON.stringify(data)).digest('hex');
  const title = chinese ? '工具包执行示例' : 'Executed library examples';
  const note = chinese ? '由 hapin-utils 5.0.0 执行生成的固定版本快照，使用 context-v1 规则。stable 表示正式版本通道，发布动作由维护者执行。' : 'A fixed snapshot generated by executing hapin-utils 5.0.0 with context-v1 rules. The stable channel identifies the version; publication is a separate maintainer action.';
  const show = value => String(value).replace(/\u200b/g, '\\u200b').replace(/\n/g, '\\n').replace(/\t/g, '\\t').replace(/\|/g, '&#124;');
  const rows = data.examples.map(e => '| ' + e.id + ' | `' + show(e.input) + '` | `' + show(e.text) + '` | ' + e.status + ' |');
  return ['---', 'title: ' + title, 'order: 3', '---', '', '<!-- snapshot-sha256:' + digest + ' -->', '', note, '',
    'Package: ' + data.packageVersion + '; rules: ' + data.rulesVersion + '; status: ' + data.releaseStatus + '.', '',
    '| ID | Input | Output | Status |', '| --- | --- | --- | --- |', ...rows, ''].join('\n');
}
